package config

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// Pre-fork names are kept in this file only, so the rest of the codebase and
// every user-visible string use the QingyuGist identity. They exist solely to
// keep an existing installation's data, environment and git hooks working
// after upgrading.
const (
	legacyName       = "opengist"
	legacyHomeEnv    = "OG_OPENGIST_HOME"
	legacyEnvPrefix  = "OG_"
	legacySecretName = legacyName + "-secret.key"
	legacyHostKey    = legacyName + "-ed25519"
	legacyDatabase   = legacyName + ".db"
	legacyIndexDir   = legacyName + ".index"
)

// LegacyExecutableName is the binary name used before the fork. Existing git
// hooks and authorized_keys entries still point at it.
const LegacyExecutableName = legacyName

// envLookup reads the QingyuGist variable first, then the pre-fork equivalent.
// This lets an existing deployment keep its environment file while new installs
// use the QYG_ namespace.
func envLookup(name string) (string, bool) {
	if value, ok := os.LookupEnv(name); ok {
		return value, true
	}

	legacy := ""
	if strings.HasPrefix(name, "QYG_") {
		suffix := strings.TrimPrefix(name, "QYG_")
		if suffix == "HOME" {
			legacy = legacyHomeEnv
		} else {
			legacy = legacyEnvPrefix + suffix
		}
	}
	if legacy == "" {
		return "", false
	}
	return os.LookupEnv(legacy)
}

// migrateLegacyData upgrades on-disk names in place. The SQLite file is renamed
// so the installation is fully rebranded; if the rename is not possible (for
// example, a file lock on Windows), the old path is kept so no data is lost.
func migrateLegacyData(out io.Writer) {
	home := GetHomeDir()

	// A config file copied from the pre-fork project can still name the old
	// database. Move it to the new name as well, so upgrading is not limited to
	// installs that use the new default.
	if filepath.Base(C.DBUri) == legacyDatabase {
		wasAbsolute := filepath.IsAbs(C.DBUri)
		dir := home
		if wasAbsolute {
			dir = filepath.Dir(C.DBUri)
		}
		legacy := filepath.Join(dir, legacyDatabase)
		current := filepath.Join(dir, "qingyugist.db")
		if !pathExists(current) && pathExists(legacy) {
			if err := os.Rename(legacy, current); err == nil {
				_ = os.Rename(legacy+"-wal", current+"-wal")
				_ = os.Rename(legacy+"-shm", current+"-shm")
				C.DBUri = "qingyugist.db"
				if wasAbsolute {
					C.DBUri = current
				}
				_, _ = fmt.Fprintf(out, "Migrated database to %s\n", current)
			} else {
				C.DBUri = legacy
				_, _ = fmt.Fprintf(out, "Using existing database at %s (could not rename it: %v)\n", legacy, err)
			}
		}
	}

	if home != "" && !pathExists(filepath.Join(home, "qingyugist-secret.key")) {
		legacy := filepath.Join(home, legacySecretName)
		if pathExists(legacy) {
			if err := MigrateLegacyFile(filepath.Join(home, "qingyugist-secret.key"), legacy); err == nil {
				_, _ = fmt.Fprintf(out, "Migrated session secret to qingyugist-secret.key\n")
			}
		}
	}

	// Keeping the old search index avoids a cold search after the upgrade.
	if home != "" {
		legacy := filepath.Join(home, legacyIndexDir)
		current := filepath.Join(home, "qingyugist.index")
		if !pathExists(current) && pathExists(legacy) {
			if err := os.Rename(legacy, current); err == nil {
				_, _ = fmt.Fprintf(out, "Migrated search index to qingyugist.index\n")
			}
		}
	}
}

// MigrateLegacyFile copies oldPath to newPath when newPath does not exist yet.
// Copying (rather than renaming) means a rollback to the pre-fork binary still
// finds its session key, SSH host key and other state.
func MigrateLegacyFile(newPath, oldPath string) error {
	if pathExists(newPath) || !pathExists(oldPath) {
		return nil
	}
	data, err := os.ReadFile(oldPath)
	if err != nil {
		return err
	}
	return os.WriteFile(newPath, data, 0600)
}

// ExportLegacyEnv keeps git hooks generated by the pre-fork binary working.
// Those hooks locate the executable through the old home variable.
func ExportLegacyEnv() {
	if home := GetHomeDir(); home != "" {
		_ = os.Setenv("OG_OPENGIST_HOME_INTERNAL", home)
	}
}

// Env reads a QYG_ variable with a fallback to its pre-fork name.
func Env(name string) string {
	value, _ := envLookup(name)
	return value
}

func pathExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}
